const PET_NAMES_BY_SPECIES: Record<PetSpeciesKind, readonly WeightedName[]> = {
  dog: DOG_PET_NAMES,
  cat: CAT_PET_NAMES,
  other: OTHER_PET_NAMES,
};

/** Pick a display name weighted by US-style popularity for the species. */
export function pickPetDisplayName(
  species: PetSpeciesKind,
  rng: () => number,
): string {
  return pickWeightedFromPool(PET_NAMES_BY_SPECIES[species], rng);
}

function pickWeightedFromPool(
  items: readonly WeightedName[],
  rng: () => number,
): string {
  const total = items.reduce((sum, item) => sum + item.weight, 0);
  let roll = rng() * total;
  for (const item of items) {
    roll -= item.weight;
    if (roll <= 0) return item.name;
  }
  return items[items.length - 1].name;
}

