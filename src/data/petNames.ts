/**
 * US pet name popularity (Rover 2024, TrustedHousesitters 2025, AKC 2025).
 * Weights decay by rank so Luna/Bella/Charlie dominate; rare joke names sit at 1–3.
 */

function namesWithRankWeights(
  names: readonly string[],
  topWeight = 100,
  decay = 0.965,
  minWeight = 1,
): WeightedName[] {
  return names.map((name, index) => ({
    name,
    weight: Math.max(
      minWeight,
      Math.round(topWeight * decay ** index),
    ),
  }));
}

