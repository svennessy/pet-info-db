function dedupeNames(entries: WeightedName[]): WeightedName[] {
  const byName = new Map<string, number>();
  for (const entry of entries) {
    const key = entry.name.toLowerCase();
    byName.set(key, Math.max(byName.get(key) ?? 0, entry.weight));
  }
  return [...byName.entries()].map(([key, weight]) => {
    const original = entries.find((e) => e.name.toLowerCase() === key);
    return { name: original!.name, weight };
  });
}

